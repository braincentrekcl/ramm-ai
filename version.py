"""Bump RAMM-AI's version in every file that holds it, for maintainers at a release.

Usage, from the repository root:

    python3 version.py 0.3.1

The current version is read from VERSION, the one source for it, and the new
one is written there and copied to every other place.
Every place is checked before any file is written, so a place that does not
hold the current version stops the bump with nothing changed.
Do not edit VERSION by hand first.
The script would then look for the new version everywhere else, and stop.
"""

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
VERSION_PATTERN = re.compile(r"\d+\.\d+\.\d+")

# Each place is a file, the text around the version, and how many times it appears.
PLACES = (
    ("VERSION", "{version}", 1),
    (".claude-plugin/plugin.json", '"version": "{version}"', 1),
    (".codex-plugin/plugin.json", '"version": "{version}"', 1),
    ("skills/ramm/references/script.md", "Generated by RAMM-AI {version} ", 1),
    ("skills/ramm/references/script.md", 'value = c("{version}", ', 1),
    (
        "skills/reproduce/references/container.md",
        "Generated by the RAMM-AI {version} reproduce skill",
        2,
    ),
    (
        "skills/reproduce/references/renv.md",
        "Generated by the RAMM-AI {version} reproduce skill",
        1,
    ),
)


def current_version(root: Path) -> str:
    return (root / "VERSION").read_text(encoding="utf-8").strip()


def bump(root: Path, new_version: str) -> list[Path]:
    """Replace the current version with new_version in every place; return the files written."""
    if not VERSION_PATTERN.fullmatch(new_version):
        raise ValueError(
            f"'{new_version}' is not a version in the form MAJOR.MINOR.PATCH"
        )
    old_version = current_version(root)
    texts: dict[Path, str] = {}
    for relative_path, template, expected_count in PLACES:
        path = root / relative_path
        # Bytes, not text, so line endings stay as they are on every platform.
        text = texts.get(path, path.read_bytes().decode("utf-8"))
        old_text = template.format(version=old_version)
        found = text.count(old_text)
        if found != expected_count:
            raise ValueError(
                f"{relative_path}: expected {expected_count} of '{old_text}', found {found}"
            )
        texts[path] = text.replace(old_text, template.format(version=new_version))
    for path, text in texts.items():
        path.write_bytes(text.encode("utf-8"))
    return list(texts)


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    old_version = current_version(REPO_ROOT)
    written = bump(REPO_ROOT, argv[0])
    print(f"Bumped {old_version} to {argv[0]} in:")
    for path in written:
        print(f"  {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
